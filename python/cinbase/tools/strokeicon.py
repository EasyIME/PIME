"""Deterministic offline renderer for the 筆畫輸入法 (PIME) Service icon.

The icon depicts the five stroke glyphs of the Five-stroke keyset in key order,
top to bottom: 一 (``h``, 橫), 丨 (``s``, 豎), 丿 (``p``, 撇), 丶 (``n``, 點),
乙 (``z``, 折).  Everything is integer arithmetic on a fixed grid so two runs
over the same tree write the same bytes; no third-party image library is
needed, which is what lets the installer build stay offline.

Run from the repository root::

    python/python3/python.exe python/cinbase/tools/strokeicon.py

which rewrites ``python/input_methods/chebihua/icon.png`` (48x48 RGBA, the
settings page) and ``python/input_methods/chebihua/icon.ico`` (32x32 32bpp, the
name ``ime.json`` names for the TSF icon).

Fully generated by omp (Qwen3.8-Flash-Next) without human creative authorship.
SPDX-License-Identifier: LGPL-2.1-or-later
"""

import os
import struct
import zlib

# Each glyph is a list of segment pairs in unit coordinates of one square cell.
# The 點 is a short, thick segment; 乙 is the turn, drawn as its three straight
# runs plus the upturned tail so the shape stays readable at 32 px.
GLYPH_SEGMENTS = (
    # 一 橫
    (((0.10, 0.50), (0.90, 0.50)),),
    # 丨 豎
    (((0.50, 0.10), (0.50, 0.90)),),
    # 丿 撇
    (((0.75, 0.12), (0.25, 0.88)),),
    # 丶 點
    (((0.42, 0.38), (0.62, 0.62)), ((0.42, 0.50), (0.62, 0.50))),
    # 乙 折
    (((0.18, 0.16), (0.82, 0.16)),
     ((0.82, 0.16), (0.30, 0.62)),
     ((0.30, 0.62), (0.86, 0.86)),
     ((0.86, 0.86), (0.90, 0.70))),
)

PNG_SIZE = 48
ICO_SIZE = 32
INK = (0, 0, 0, 255)


def _cell(size, index):
    """Return the (offset, side) of glyph ``index`` in a ``size`` grid."""
    side = size // 5
    return index * side, side


def _plot(grid, size, x, y, value):
    if 0 <= x < size and 0 <= y < size:
        grid[y][x] = value


def _segment(grid, size, p0, p1, base, side, value):
    """Rasterise one unit-coordinate segment into the cell at ``base``."""
    (x0, y0), (x1, y1) = p0, p1
    span = max(side - 2, 1)
    ax = base[0] + 1 + int(round(x0 * (span - 1)))
    ay = base[1] + 1 + int(round(y0 * (span - 1)))
    bx = base[0] + 1 + int(round(x1 * (span - 1)))
    by = base[1] + 1 + int(round(y1 * (span - 1)))
    steps = max(abs(bx - ax), abs(by - ay), 1)
    for step in range(steps + 1):
        t = step / steps
        px = ax + int(round((bx - ax) * t))
        py = ay + int(round((by - ay) * t))
        _plot(grid, size, px, py, value)
        # The 點 and the 橫 read better one pixel thick at these sizes.
        _plot(grid, size, px, py + 1, value)


def raster(size):
    """The five stroke glyphs, one per horizontal band, top to bottom."""
    grid = [[0] * size for _ in range(size)]
    for index, segments in enumerate(GLYPH_SEGMENTS):
        offset, side = _cell(size, index)
        for segment in segments:
            _segment(grid, size, segment[0], segment[1], (offset, offset),
                     side, 1)
    return grid


def png_bytes(size=PNG_SIZE):
    """A minimal RGBA PNG: IHDR, one IDAT, IEND, no optional chunks."""
    grid = raster(size)
    raw = bytearray()
    for row in grid:
        raw.append(0)  # the None filter, one per scanline
        for cell in row:
            raw.extend(INK if cell else (0, 0, 0, 0))
    chunks = [
        (b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)),
        (b"IDAT", zlib.compress(bytes(raw), 9)),
        (b"IEND", b""),
    ]
    out = bytearray(b"\x89PNG\r\n\x1a\n")
    for kind, body in chunks:
        out.extend(struct.pack(">I", len(body)))
        out.extend(kind)
        out.extend(body)
        out.extend(struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF))
    return bytes(out)


def ico_bytes(size=ICO_SIZE):
    """One 32bpp top-down-free BMP entry, the form ``LoadImage`` expects."""
    grid = raster(size)
    dib = bytearray()
    dib += struct.pack("<IiiHHIIiiII", 40, size, size, 1, 32, 0,
                       40 + size * size * 4 + size * 4, 0, 0, 0, 0)
    # Bottom-up rows, BGRA, ink opaque and the rest transparent black.
    for row in reversed(grid):
        for cell in row:
            dib += bytes((0, 0, 0, 255)) if cell else bytes((0, 0, 0, 0))
    # AND mask: one bit per pixel, every row padded to a 32-bit word.
    mask = bytearray()
    words = (size + 31) // 32
    for row in grid:
        bits = 0
        for shift, cell in enumerate(row):
            if not cell:
                bits |= 1 << (size - 1 - shift)
        for word in range(words):
            for k in range(4):
                mask.append((bits >> (8 * (3 - k) + 8 * (words - 1 - word))) & 0xFF)
    image = bytes(dib) + bytes(mask)
    header = struct.pack("<HHH", 0, 1, 1)
    entry = struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32,
                        len(image), len(header) + 16)
    return header + entry + image


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    service_dir = os.path.normpath(
        os.path.join(here, os.pardir, os.pardir, "input_methods", "chebihua"))
    written = []
    for name, payload in (("icon.png", png_bytes()),
                          ("icon.ico", ico_bytes())):
        path = os.path.join(service_dir, name)
        with open(path, "wb") as handle:
            handle.write(payload)
        written.append((name, len(payload)))
    for name, length in written:
        print("%s %d bytes" % (name, length))


if __name__ == "__main__":
    main()
